/* ==========================================================================
   assets/js/music.config.js · 云村页面的可调项
   ---------------------------------------------------------------------------
   这个文件是给「页面」看的，不涉及任何密钥。
   登录凭证全部由本机小服务（tools/ncm-server.mjs）保管，浏览器这边一个字节都不存。
   部署到线上时，把 service 改成你放小服务的地址即可。
   ========================================================================== */
window.CV01_MUSIC = {
  /* 本机小服务的地址。跑 `node tools/ncm-server.mjs` 时默认就是这个。
     想换成远程：service: 'https://ncm.example.com' */
  service: 'http://127.0.0.1:3170',

  /* 每页加载多少首红心歌 */
  pageSize: 50,

  /* 扫码轮询间隔（毫秒）。太密会被网易风控，2 秒是社区通行的稳妥值。 */
  pollInterval: 2000,

  /* 二维码显示多久后自动换一张（秒）。
     这个值是"页面多久换一次"，不是"二维码什么时候作废"——网易那边的有效期由它自己定，
     通常比这长。给 300 秒是为了别在人家掏手机的时候把码换掉。
     真过期了也不用管：页面会自己无声换新（见 kumura.js 的 expireQr）。 */
  qrTtl: 300,

  /* 单个请求的超时（毫秒）。指向没人监听的端口时，没有这个就会一直卡在"正在连接"。 */
  timeout: 8000,
};
